// Token Radar — the token-radar-01 entry (Node 22, standard library only).
//
// The program reads the sealed DefiLlama snapshot, ranks every rankable
// pre-token protocol by what its launch would be worth, and writes the board,
// the dashboard's data, the dashboard, the screenshots and the judge's dossier
// to /output. Nothing is fetched: the snapshot is the only data, and every
// number below is derived from its own figures.
//
// Model "radar-2" (stated in the dashboard, no protocol name ever special-cased):
//   multiple  = median(mcap_usd / tvl_usd) of the live-token protocols in the
//               same category (at least 5 of them), else the global median;
//               clamped to [0.05, 3.0] so one outlier cannot set the price
//   growth    = 1 + clamp(change_7d, -60, 120) / 100 * 0.5
//   maturity  = 0.6 + min(age_days, 1095) / 1095 * 0.4   (unknown age: 365)
//   breadth   = 1 + 0.02 * min(chains - 1, 5)
//   implied   = max(1, round(tvl_usd * multiple * growth * maturity * breadth))
//
// The multiple is the model's whole point: a token is worth what the market
// already pays for the same kind of protocol, per dollar of TVL. A lending
// protocol is priced like lending protocols, a DEX like DEXes, and a category
// with too few live tokens to price falls back to the whole market's median.
//
// The board ranks every protocol the watchlist's own rule would keep (the 40
// on the watchlist plus every other pre-token protocol that is not a wrapped,
// staked or bridged product, not a versioned pool and not an exchange), so the
// radar covers the floor and everything below it that can still launch.
//
// Run it:
//   mkdir -p out && MAKEFUN_OUTPUT_DIR=out node main.ts --input ../input/snapshot.json

